"""Original deterministic pixel textures and native Minecraft models. Requires Pillow."""
from pathlib import Path
from PIL import Image, ImageDraw
import json, math
root=Path(__file__).resolve().parents[1]/'src/main/resources/assets/omni_display'
def put(path,obj):
 p=root/path;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps(obj,ensure_ascii=False,indent=2))
tex=root/'textures/block';tex.mkdir(parents=True,exist_ok=True)
# Seamless 64x64 periodic hex lattice, no per-block border. Coordinates repeat exactly.
def screen(w,h):
 im=Image.new('RGB',(w*4,h*4),(4,6,8));d=ImageDraw.Draw(im)
 for col in range(-1,w//16+2):
  for row in range(-1,h//16+2):
   x=col*16;y=row*16+(col%2)*8
   vertices=[(x-11,y),(x-5,y-8),(x+5,y-8),(x+11,y),(x+5,y+8),(x-5,y+8)]
   d.polygon([(x*4,y*4) for x,y in vertices],fill=(5,7,10),outline=(12,18,22),width=1)
 return im
screen(64,64).save(tex/'screen_hex.png')
im=Image.new('RGB',(64,64),(32,44,55));d=ImageDraw.Draw(im)
d.rectangle((1,1,62,62),outline=(61,79,90));d.rectangle((3,3,60,60),outline=(18,25,33))
# Recessed routing channels with copper and blue insulated cables.
for x in (10,20,48):
 d.line([(x,0),(x,20),(x+5,25),(x+5,43),(x,48),(x,63)],fill=(9,15,21),width=7)
 d.line([(x,0),(x,20),(x+5,25),(x+5,43),(x,48),(x,63)],fill=(70,83,90) if x==48 else (55,75,92),width=3)
 d.line([(x-1,0),(x-1,19)],fill=(102,113,118),width=1)
d.rounded_rectangle((28,17,43,43),radius=2,fill=(15,22,29),outline=(80,93,101))
for y in range(21,41,4):d.line((31,y,40,y),fill=(59,69,75))
for x,y in ((5,5),(58,5),(5,58),(58,58)):
 d.rectangle((x-1,y-1,x+1,y+1),fill=(108,119,125));d.point((x,y),fill=(23,29,35))
d.rectangle((29,48,39,54),fill=(65,47,28),outline=(106,77,42));d.line((30,51,38,51),fill=(161,111,49))
