for x in (0,15,32,47,63):ds.line((x,0,x,63),fill=(64,81,92))
side.save(tex/'door_edge.png')
faces=['down','up','north','south','west','east']
variants={}
for mask in range(64):
 name=f'display_{mask}'
 textures={face:'omni_display:block/'+('screen_hex' if mask&(1<<i) else 'screen_back') for i,face in enumerate(faces)}
 textures['particle']='omni_display:block/screen_back'
 put(Path('models/block')/(name+'.json'),{'parent':'minecraft:block/cube','textures':textures})
 variants[f'screen_faces={mask}']={'model':'omni_display:block/'+name}
put(Path('blockstates/display.json'),{'variants':variants})
put(Path('models/block/display.json'),{'parent':'omni_display:block/display_4'})
# East/West broad faces correspond to FACING/opposite in the base east-facing door model.
# Native model geometry is authored here, matching the 3/16 thickness and full height.
for mask in range(4):
 for half in ('lower','upper'):
  elements={'from':[0,0,0],'to':[3,16,16],'faces':{}}
  for face in faces:
   if (half=='upper' and face=='down') or (half=='lower' and face=='up'):continue
   texture='edge'
   if face=='east':texture='front'
   if face=='west':texture='back'
   elements['faces'][face]={'uv':[0,0,16,16],'texture':'#'+texture}
  put(Path('models/block')/f'door_{half}_{mask}.json',{'parent':'minecraft:block/block','textures':{
   'front':'omni_display:block/'+('screen_hex' if mask&1 else 'screen_back'),
   'back':'omni_display:block/'+('screen_hex' if mask&2 else 'screen_back'),
   'edge':'omni_display:block/door_edge','particle':'omni_display:block/screen_back'},'elements':[elements]})
